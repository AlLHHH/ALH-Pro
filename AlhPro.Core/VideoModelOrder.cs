namespace AlhPro.Core;

/// <summary>视频页「超分模型」下拉的**序号迁移**(纯逻辑,可单测)。
///
/// 【为什么需要它】这个下拉保存的是**序号**(<c>VideoSettings.UpEsrganModel</c>),用户自建预设里也存序号。
/// 一旦调整下拉顺序,老序号就会被解释成**另一支模型**,而且是静默的:
/// 2026-09-12 那次把 general-x4v3 上移一位,老用户"存的 3 = 轻量模型"会变成"3 = x4plus"——
/// 1080p 实测 14.5 秒/帧、比 animevideov3 慢 17 倍,界面上却看不出任何异常。
/// 所以"移动过顺序"必须配一条一次性迁移,并按 Rev 逐级做(老文件从 Rev0 一路换到最新)。
///
/// 【顺序变更史(每次改顺序都要 +1 Rev,并在下面加一段)】
///   · Rev0 → Rev1(2026-09-12):0=animevideov3, 1=x4plus-anime, 2=x4plus, 3=general-x4v3
///                               → 0=animevideov3, 1=x4plus-anime, 2=general-x4v3, 3=x4plus
///   · Rev1 → Rev2(2026-09-13):把 general-x4v3 移到 animevideov3 正下方
///                               → 0=animevideov3, 1=general-x4v3, 2=x4plus-anime, 3=x4plus
///   · Rev2 → Rev3(2026-09-14):新增 wdn-x4v3,并按**速度与体积**重排(快/小 → 慢/大)
///                               → 0=animevideov3(4MB, 0.26~0.30 s/帧)
///                                 1=general-x4v3  (5MB, 0.458)
///                                 2=wdn-x4v3      (5MB, 0.460)
///                                 3=x4plus-anime  (9MB, 3.85)
///                                 4=x4plus        (41MB, 15.87, 超慢稳居最后)
///     ⇒ 映射:2→3、3→4、4→2(4 是 Rev2 里刚加的 wdn,它要挪到第 2 位),0/1 不变。
///   · Rev3 → Rev4(2026-09-15):**末尾追加**两个自训的 2x 模型(权重 pth→ncnn,用户定名见下),
///                              老 5 项的位置一个都不动
///                               → 0=animevideov3, 1=general-x4v3, 2=wdn-x4v3, 3=x4plus-anime, 4=x4plus,
///                                 5=alhpro-real2x(现实向)  6=alhpro-game2x(游戏向)
///     ⇒ 映射:**恒等**(0..4 原地不动;老文件不可能存过 5/6,越界兜底那条路照旧归 0)。
///       之所以能恒等,是因为这次只"追加"、不"换位" —— 与 Rev2 期间加 wdn 的手法相同,
///       也是本仓库认可的最安全的加模型方式:老用户存的序号含义不变,升级后模型不会跳。
///      【命名 · 用户 2026-09-15 定】界面文字只许叫「游戏向」「现实向」,不出现"实验"字样;
///      括号里写实测速度(口径与数值见 AlhPro.Core.ExperimentalEsrgan)。
///
///   · Rev4 → Rev5(2026-09-19):**末尾追加**一支自训 2x 模型「游戏 · alhgame2x-v2」(用用户 26 段录像重训,
///                               实测全面优于 v1;v1 保留不动),老 7 项位置一个都不动
///                               → 0..6 与 Rev4 逐位相同,7=alhpro-game2x-v2
///     ⇒ 映射:**恒等**(0..6 原地不动;老文件不可能存过 7,越界兜底那条路照旧归 0)。
///       与 Rev3→Rev4 同一手法:只"追加"不"换位",是老用户最安全的加模型方式。
///
/// 【Rev2 期间的 wdn 为什么在 4 位】该模型先以"末尾追加"的方式上线(追加不动老序号,最安全);
/// 用户随后要求按速度/体积排,才引出 Rev3 这次真正的换位。</summary>
public static class VideoModelOrder
{
    /// <summary>当前下拉顺序对应的 Rev。改顺序必须 +1,并同步 XAML 与 <c>UpEsrganModelNames</c>。</summary>
    public const int CurrentRev = 10;

    /// <summary>下拉项数量(0..Count-1)。Rev10 = Rev9 的 8 项 + 末尾**追加**的 2 个 1x 修复条目
    /// (「动漫 · Anime4K 修复」「现实 · 1x 修复」)—— 用户:"1x 也是可以选模型 加一个现实的1x模型"。</summary>
    public const int Count = 10;

    /// <summary>1x 修复两个条目的**固定序号**(Rev10 起;它们永远是列表最后两项)。
    /// 【为什么要具名常量】官方预设要引用"选中 Anime4K 那一档"(见 VideoView.BuiltinPresets 里新增的
    /// 「1x 修复（不放大）」),写魔法数字 8/9 的话,以后谁再动顺序都不会被任何人发现 ✗。
    /// 单测按"下拉里各条目的 Tag 顺序"钉住这两个值与其对应关系(见 VideoModelOrderTests)。</summary>
    public const int Anime4kIndex = 8;
    /// <summary>「现实 · 1x 修复」在列表里的序号(见上)。</summary>
    public const int Real1xIndex = 9;

    /// <summary>把某个 Rev 下保存的序号换算成当前 Rev 的序号。
    /// <paramref name="rev"/> 为该数据写入时的 Rev(读出来即 <c>ModelOrderRev</c>)。
    /// 返回换算后的序号;<paramref name="newRev"/> 出参为换算后应写回的 Rev。
    /// 幂等:传入已是 <see cref="CurrentRev"/> 的数据原样返回。</summary>
    public static int Migrate(int model, int rev, out int newRev)
    {
        int m = model;
        if (rev < 1)
        {
            // Rev1:x4plus(超慢) ↔ general-x4v3 互换
            if (m == 2) m = 3;
            else if (m == 3) m = 2;
            rev = 1;
        }
        if (rev < 2)
        {
            // Rev2:x4plus-anime ↔ general-x4v3 互换(把 general-x4v3 移到 animevideov3 正下方)
            if (m == 1) m = 2;
            else if (m == 2) m = 1;
            rev = 2;
        }
        if (rev < 3)
        {
            // Rev3:插入 wdn-x4v3 并按速度/体积重排 —— 2→3、3→4、4(=wdn)→2
            m = m switch { 2 => 3, 3 => 4, 4 => 2, _ => m };
            rev = 3;
        }
        if (rev < 4)
        {
            // Rev4:末尾追加两个自训模型(5=alhpro-real2x 现实向、6=alhpro-game2x 游戏向)⇒ **恒等映射**,老序号含义不变。
            // 【为什么这里什么都不做也要留一段】① 版本号必须前进:不写 rev=4 的话,文件每次都"版本落后",
            //   每次启动都重写一次设置文件;② 留一段空的映射是在明确声明"这次没有换位",
            //   下一个人要加模型时能照着这段抄(本仓库的既有约定:Rev 与映射一一对应,注释里写清为什么恒等)。
            // ⚠ 若日后有人把新模型**插到中间**(而不是追加),这里必须补上真正的换位映射,否则老序号会静默指向别的模型。
            rev = 4;
        }
        if (rev < 5)
        {
            // Rev5:末尾**追加**「游戏 · alhgame2x-v2」(alhpro-game2x-v2)⇒ **恒等映射**,0..6 含义一个都没变。
            // 【与 Rev4 同一手法】只追加、不换位 ⇒ 老用户存的序号(含自建预设里的序号)升级后不会指向别的模型。
            // ⚠ 日后若把新模型插到中间,这里必须补真正的换位映射(本仓库的既有约定:Rev 与映射一一对应)。
            rev = 5;
        }
        if (rev < 6)
        {
            // Rev6:末尾**追加**「游戏 · alhgame2x-v3」(alhpro-game2x-v3,锐化优先那一支)⇒ **恒等映射**,0..7 含义不变。
            // 【2026-09-21 改名不动 Rev】四项自训模型只是**界面显示名**加了 `alh` 前缀(权重文件名/Tag/序号都没动),
            //   保存的是序号 ⇒ **不需要 +1 Rev、不需要新映射**(Rev 只管"顺序",改名不改顺序)。
            // 【⚠ 顺序纪律 · 本条踩过一次】各段必须**按 rev 升序**排列:谁先谁后不是风格问题 ——
            // 若把 `rev = 6` 写到 `if (rev < 5)` 之前,Rev2 的老文件会先吃到 `rev=6`,后面 rev<5 那段就被跳过,
            // **Rev3 的换位映射整个失效**(老序号静默指向别的模型)。真机差点带着这个错打包上线。
            rev = 6;
        }
        if (rev < 7)
        {
            // Rev7:**移除**「游戏 · alhgame2x」(v1) —— 用户 2026-09-21:"不要训练那么多模型了 我要留两个最好的游戏 1个现实就行"。
            //   移除的是**中间/末段**的项 ⇒ 后面的序号整体前移,必须给映射(这是本仓库第一次做"移除"而不是"追加"):
            //     旧 0..5 不动;
            //     旧 6 = alhpro-game2x(已移除)  → 6 = alhpro-game2x-v2(**同族里最保真的那支**,严格优于 v1:
            //                                     实测 PSNR 32.67 对 31.62、detail 672 对 288)
            //     旧 7 = alhpro-game2x-v2       → 6
            //     旧 8 = alhpro-game2x-v3       → 7
            //   ⇒ 老用户"存的 7(v2)"仍然是 v2、"存的 8(v3)"仍然是 v3;只有选了被移除那支的人被挪到 v2(只升不降)。
            m = m switch { 6 => 6, 7 => 6, 8 => 7, _ => m };
            rev = 7;
        }
        if (rev < 8)
        {
            // Rev8(已作废,保留这一段的"历史语义"说明):曾在末尾**追加**「动漫 · Anime4K 修复」(Tag = anime4k),
            //   恒等映射,0..7 含义没变 —— 所以从更早的版本上来的数据,这一段不需要换算。
            rev = 8;
        }
        if (rev < 9)
        {
            // Rev9:**把 Anime4K 从模型列表里拿掉** —— 用户 2026-09-21:"an4K 那个不在列表显示 只在选择 1x 时模型锁住并显示"。
            //   它本来就不是放大模型(没有权重、不放大),挂在列表里会让"想放大的人"选到它。
            //   现在改为:**选 1x 修复时把模型框锁住、显示 Anime4K**(见 VideoView 的联动)。
            //   序号影响:旧 8 = anime4k(已不在列表) → 0 = animevideov3(最快最省、也是官方默认那一支);
            //   0..7 一个都没动(Anime4K 当初就是**末尾追加**的)⇒ 老用户存的模型选择全都不会错位。
            //   ⚠ 不留这条映射的后果:存过 8 的人会拿到"越界值"⇒ 被兜底成 0(碰巧同一个结果),
            //     但日志里会看不见"为什么变回 animevideov3",所以显式写出来 + 记日志。
            if (m == 8) m = 0;
            rev = 9;
        }
        if (rev < 10)
        {
            // Rev10:末尾**追加**两个 1x 修复条目(「动漫 · Anime4K 修复」= anime4k、「现实 · 1x 修复」= alhpro-real1x)
            //   —— 用户 2026-09-21:"1x 也是可以选模型 加一个现实的1x模型"。
            //   两者都是**末尾追加** ⇒ 0..7 含义一个字都没变 ⇒ **恒等映射**(老用户存的放大模型选择全不受影响)。
            //   ⚠ Rev9 曾把 anime4k 从列表里拿掉(改 id 8→0);Rev10 又把它作为**末尾新项**加回来 ——
            //     序号不会回到 8(现在是 8/9),所以 Rev9 的映射必须保留在它前面(顺序纪律:各段按 rev 升序)。
            rev = 10;
        }
        newRev = rev;
        // 越界值(手改坏/未来版本回退)保守归到 0(animevideov3,最快最省那一支),不猜中间项
        return m is >= 0 and < Count ? m : 0;
    }
}
