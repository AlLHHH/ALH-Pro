///   ⇒ 两支都在 **0.35 秒/帧** 一档(与官方 animevideov3 同档;两支自身同架构同体积,测不出差异)。
///   界面写 **0.35**(取多次冷跑里最稳的那一档=14.03s/40 帧,**不写 0.376/0.368 这种假精度**)。
///   ⚠ 成本表里官方 animevideov3 2x 记的是 0.252~0.269,比本次同口径实测快约 1.3 倍 ——
